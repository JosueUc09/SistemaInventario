create or replace function public.rol_actual()
returns text language sql stable security definer set search_path = public
as $$
  select r.nombre from public.perfiles p
  join public.roles r on r.id = p.role_id
  where p.id = auth.uid() and p.activo = true
$$;

create or replace function public.puede_administrar_inventario()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.rol_actual() in ('Administrador', 'Administrativo'), false) $$;

create or replace function public.registrar_auditoria()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  encabezados jsonb := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  fila_id text;
  modulo_nombre text;
begin
  fila_id := coalesce((case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end)->>'id', '');
  modulo_nombre := case tg_table_name
    when 'activos' then 'Inventario'
    when 'perfiles' then 'Usuarios'
    when 'mantenimientos' then 'Mantenimientos'
    else initcap(tg_table_name)
  end;

  insert into public.auditorias
    (usuario_id, modulo, accion, entidad, registro_id, valor_anterior, valor_nuevo, equipo)
  values
    (auth.uid(), modulo_nombre,
     case tg_op when 'INSERT' then 'Agregar' when 'UPDATE' then 'Editar' else 'Eliminar' end,
     tg_table_name, fila_id,
     case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,
     case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end,
     coalesce(encabezados->>'x-client-machine', 'No informado'));
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists auditar_activos on public.activos;
create trigger auditar_activos after insert or update or delete on public.activos
for each row execute function public.registrar_auditoria();
drop trigger if exists auditar_perfiles on public.perfiles;
create trigger auditar_perfiles after insert or update or delete on public.perfiles
for each row execute function public.registrar_auditoria();
drop trigger if exists auditar_mantenimientos on public.mantenimientos;
create trigger auditar_mantenimientos after insert or update or delete on public.mantenimientos
for each row execute function public.registrar_auditoria();

