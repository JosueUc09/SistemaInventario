drop policy if exists ubicaciones_lectura on public.ubicaciones;
create policy ubicaciones_lectura on public.ubicaciones for select to authenticated using (true);
drop policy if exists estados_lectura on public.estados_activo;
create policy estados_lectura on public.estados_activo for select to authenticated using (true);

