drop policy if exists roles_lectura on public.roles;
create policy roles_lectura on public.roles for select to authenticated using (true);
drop policy if exists perfiles_lectura on public.perfiles;
create policy perfiles_lectura on public.perfiles for select to authenticated
using (id = auth.uid() or public.rol_actual() = 'Administrador');
drop policy if exists perfiles_actualizar_admin on public.perfiles;
create policy perfiles_actualizar_admin on public.perfiles for update to authenticated
using (public.rol_actual() = 'Administrador') with check (public.rol_actual() = 'Administrador');

