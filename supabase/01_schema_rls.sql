  public.perfiles, public.activos, public.mantenimientos, public.auditorias to authenticated;
grant insert, update on public.activos, public.mantenimientos to authenticated;
grant update on public.perfiles to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke insert, update, delete on public.auditorias from authenticated, anon;

