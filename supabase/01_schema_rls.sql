create table if not exists public.roles (
  id integer generated by default as identity primary key,
  nombre text not null unique
);

create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null,
  correo text not null unique,
  role_id integer not null references public.roles(id),
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.categorias (
  id integer generated by default as identity primary key,
  nombre text not null unique
);

create table if not exists public.ubicaciones (
  id integer generated by default as identity primary key,
  nombre text not null unique
);

create table if not exists public.estados_activo (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  color text not null default '#6B7280'
);

create table if not exists public.activos (
  id integer generated by default as identity primary key,
  numero_serie text not null unique,
  numero_activo text not null unique,
  nombre text not null,
  descripcion text not null default '',
  cantidad integer not null default 1 check (cantidad > 0),
  categoria_id integer not null references public.categorias(id),
  ubicacion_id integer not null references public.ubicaciones(id),
  estado_activo_id integer not null references public.estados_activo(id),
  activo_registro boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz
);

create table if not exists public.mantenimientos (
  id integer generated by default as identity primary key,
  activo_id integer not null references public.activos(id),
  fecha timestamptz not null,
  tipo text not null check (tipo in ('Preventivo', 'Correctivo', 'Revisión')),
  descripcion text not null,
  responsable text not null,
  resultado text not null default '',
  creado_en timestamptz not null default now()
);

create table if not exists public.auditorias (
  id bigint generated by default as identity primary key,
  usuario_id uuid references public.perfiles(id) on delete set null,
  modulo text not null,
  accion text not null,
  entidad text not null,
  registro_id text not null,
  valor_anterior jsonb,
  valor_nuevo jsonb,
  equipo text not null default 'No informado',
  fecha timestamptz not null default now()
);

