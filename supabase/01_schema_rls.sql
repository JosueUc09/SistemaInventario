with check (public.puede_administrar_inventario());
drop policy if exists activos_actualizar on public.activos;
create policy activos_actualizar on public.activos for update to authenticated
using (public.puede_administrar_inventario()) with check (public.puede_administrar_inventario());

drop policy if exists mantenimientos_lectura on public.mantenimientos;
create policy mantenimientos_lectura on public.mantenimientos for select to authenticated using (true);
drop policy if exists mantenimientos_insertar on public.mantenimientos;
create policy mantenimientos_insertar on public.mantenimientos for insert to authenticated
with check (public.puede_administrar_inventario());
drop policy if exists mantenimientos_actualizar on public.mantenimientos;
create policy mantenimientos_actualizar on public.mantenimientos for update to authenticated
using (public.puede_administrar_inventario()) with check (public.puede_administrar_inventario());

drop policy if exists auditorias_lectura_admin on public.auditorias;
create policy auditorias_lectura_admin on public.auditorias for select to authenticated
using (public.rol_actual() = 'Administrador');

grant usage on schema public to authenticated;
